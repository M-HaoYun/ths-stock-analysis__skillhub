def nav_svg(res):
    nav = res["nav_curve"]
    hs = json.load(open(HS300, encoding="utf-8"))["data"]["item"]
    hs_map = {__import__("datetime").datetime.fromtimestamp(it["date_ms"]/1000).strftime("%Y-%m-%d"): it["close_price"] for it in hs}
    dates = [d for d, _ in nav]
    hs0 = None
    hs_curve = []
    for d in dates:
        if d in hs_map:
            if hs0 is None:
                hs0 = hs_map[d]
            hs_curve.append((d, hs_map[d] / hs0))
    strat = [(d, nv) for d, nv in nav]
    W, H = 880, 300
    pad_l, pad_r, pad_t, pad_b = 46, 14, 24, 30
    all_pts = [v for _, v in strat] + [v for _, v in hs_curve]
    vmin, vmax = min(all_pts), max(all_pts)
    span = (vmax - vmin) or 1
    span += span * 0.15
    vmin -= span * 0.08
    def X(i, n): return pad_l + i / (n - 1) * (W - pad_l - pad_r)
    def Y(v): return pad_t + (1 - (v - vmin) / span) * (H - pad_t - pad_b)
    y1 = Y(1.0)
    parts = [
        f'<line x1="{pad_l}" y1="{y1:.1f}" x2="{W-pad_r}" y2="{y1:.1f}" stroke="#9aa1ad" stroke-width="1" stroke-dasharray="4 3"/>',
        f'<text x="{W-pad_r}" y="{y1-4:.1f}" text-anchor="end" font-size="10" fill="#9aa1ad">初始净值 1.0</text>',
    ]
    n = len(strat)
    pts = " ".join(f"{X(i,n):.1f},{Y(v):.1f}" for i, (_, v) in enumerate(strat))
    area = f"{pad_l},{Y(strat[0][1]):.1f} " + pts + f" {X(n-1,n):.1f},{Y(strat[0][1]):.1f}"
    parts.append(f'<polygon points="{area}" fill="url(#gStrat)" opacity="0.35"/>')
    parts.append(f'<polyline points="{pts}" fill="none" stroke="#1f3a93" stroke-width="2.2" stroke-linejoin="round"/>')
    n2 = len(hs_curve)
    pts2 = " ".join(f"{X(i,n2):.1f},{Y(v):.1f}" for i, (_, v) in enumerate(hs_curve))
    parts.append(f'<polyline points="{pts2}" fill="none" stroke="#c9a227" stroke-width="1.8" stroke-dasharray="6 3"/>')
    parts.append(f'<text x="{pad_l+8}" y="16" font-size="12" font-weight="800" fill="#1f3a93">策略净值（前复权·满仓单标的）</text>')
    parts.append(f'<text x="{pad_l+280}" y="16" font-size="12" font-weight="700" fill="#c9a227">沪深300（归一化）</text>')
    sv, hv = strat[-1][1], hs_curve[-1][1]
    tr, hs_ret = res["total_ret"], res["hs_ret"]
    parts.append(f'<text x="{X(n-1,n):.1f}" y="{Y(sv)-8:.1f}" text-anchor="end" font-size="11.5" font-weight="800" fill="#1f3a93">{sv:.2f} ({tr:+.1f}%)</text>')
    parts.append(f'<text x="{X(n2-1,n2):.1f}" y="{Y(hv)+14:.1f}" text-anchor="end" font-size="11.5" font-weight="700" fill="#a8871d">{hv:.2f} (+{hs_ret:.1f}%)</text>')
    return f'<svg viewBox="0 0 {W} {H}" width="100%" role="img" aria-label="策略净值与沪深300对比"><defs><linearGradient id="gStrat" x1="0" y1="0" x2="0" y2="1"><stop offset="0%" stop-color="#2f56c9" stop-opacity="0.5"/><stop offset="100%" stop-color="#2f56c9" stop-opacity="0.02"/></linearGradient></defs>{"".join(parts)}</svg>'

