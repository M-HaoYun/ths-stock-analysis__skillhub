def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--strategy", default="channel_break", help="strategy id（缺省=channel_break 海龟唐奇安通道突破）")
    ap.add_argument("--tag", default="", help="结果文件标签（对应引擎 --tag，用于标的池验证）")
    ap.add_argument("--out", default="", help="报告 HTML 输出目录（默认 = 工作区根目录 BASE；可用绝对/相对路径覆盖）")
    args = ap.parse_args()
    sid = args.strategy
    tag = args.tag
    out_dir = args.out if not args.out else (args.out if os.path.isabs(args.out) else os.path.join(BASE, args.out))
    os.makedirs(out_dir or ".", exist_ok=True)
    try:
        res = load_result(sid, tag)
    except (FileNotFoundError, OSError):
        # 引擎产物缺失：如实产「未取到」报告（不编造数据），保证脚本可独立运行不崩。
        _write_nodata(sid, tag, out_dir)
        return
    a = ANALYSIS[sid]
    strat = get_strat_def(sid)
    fam = strat["family"]
    verdict_good = res["total_ret"] > 0
    cnd = [t.get("cand_cnt", 0) for t in res["trades"]]
    avg_cand = round(sum(cnd) / len(cnd)) if cnd else 0
    universe = res.get("universe", "全市场")
    uni_pill = "" if universe == "全市场" else f'<span class="pill brand">标的池：{universe}</span>'
    uni_banner = "" if universe == "全市场" else (
        '<div style="margin:10px 0;padding:9px 12px;border-radius:10px;background:#fdf3e3;border:1px solid #eddcab;font-size:12px;color:#8a6d12;line-height:1.7">'
        f'⚠️ <b>标的池验证版</b>：本报告限定在 <b>{universe}</b> 单标的回测，交易笔数较少；专家分析文案（02/03/05/07 区）基于全市场回测撰写，仅作对照参考。</div>')
    note = (f"数据来源：同花顺金融数据（hithink-finance v0.1.5，本地 DuckDB v_daily_qfq 前复权日K + index history 沪深300 + symbol list 名称映射）；"
            f"回测区间 {res['dates']}~{res['dates_end']}（{res['days']} 交易日）；策略：{strat['name']}（{fam}），五要素定义见 strategies.json；"
            f"口径：涨停=前复权相邻日收益率（主板 ≥+9.8%、创业板/科创板 ≥+19.8%）；RSI14 为 SMA 均值口径 [ASSUMED]；布林=MA20±2σ（stddev_samp）；唐奇安=前 20 日最高/前 10 日最低（不含当日）；"
            f"交易按开盘价成交、满仓单标的、含单边 0.03% 费率（印花税未含）；当前资金=初始 100 万按每笔清仓收益滚动累计；总收益含期末未平仓浮动；"
            f"卖出日=信号触发日（跌超/死叉/破位等）的下一交易日，按开盘价成交；候选=选股日满足买入信号的全部股票数，均选当日成交额最大者（热度代理 [ASSUMED]）。"
            f"回测结果为历史数据模拟 [MODEL]，不代表未来表现。仅供研究参考，不构成个人投资建议。")
    html = TPL
    html = (html.replace("__TITLE_SUFFIX__", f"_{strat['name']}_{DATE.replace('-', '')}{'_' + tag if tag else ''}")
            .replace("__BT_RANGE__", f"{res['dates']} ~ {res['dates_end']}")
            .replace("__BT_DAYS__", str(res["days"]))
            .replace("__UNIVERSE_PILL__", uni_pill)
            .replace("__UNIVERSE_BANNER__", uni_banner)
            .replace("__STRATEGY__", f"{strat['name']}（{fam}）")
            .replace("__KPI_ROWS__", kpi_rows(res))
            .replace("__RULE_ROWS__", rule_rows(strat))
            .replace("__RULES_INSIGHT__", a["rules_insight"])
            .replace("__VERDICT__", a["verdict"])
            .replace("__VBADGE_CLASS__", " good" if verdict_good else "")
            .replace("__VERDICT_NOTE__", a["verdict_note"])
            .replace("__SUMMARY_ROWS__", summary_rows(a))
            .replace("__NAV_SVG__", nav_svg(res))
            .replace("__NAV_INSIGHT__", a["nav_insight"])
            .replace("__TRADE_N__", str(res["n"]))
            .replace("__TRADE_ROWS__", trade_rows(res))
            .replace("__TRADES_INSIGHT__", a["trades_insight"])
            .replace("__REASON_BARS__", reason_bars(res))
            .replace("__REASONS_INSIGHT__", a["reasons_insight"])
            .replace("__ALL_COMPARE_ROWS__", all_compare_rows(sid, tag))
            .replace("__COMPARE_INSIGHT__", a["compare_insight"])
            .replace("__OPT_ROWS__", kv_rows(a["opt"]))
            .replace("__RISK_ROWS__", kv_rows(a["risk"]))
            .replace("__NOTE__", note))
    # 文件名净化：策略名可能含 / \ : * ? " < > | 等 Windows 非法字符（如「缩量回踩 MA5/MA10」的斜杠）
    # 坑 36：不净化会直接抛 FileNotFoundError（2026-09-10 实测，缩量回踩策略报告生成失败）
    _safe_name = re.sub(r'[\\/:*?"<>|]', '-', strat['name'])
    out_path = os.path.join(out_dir or BASE, f"DuckDB回测引擎_{_safe_name}_{DATE.replace('-', '')}{'_' + tag if tag else ''}.html")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(html)
    print("策略定义:", STRATEGIES)
    print("OK ->", out_path, "| size:", len(html.encode("utf-8")))

if __name__ == "__main__":
    main()
